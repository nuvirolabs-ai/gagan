export type TranslationKey = keyof typeof english | (string & {});
export const translations = { en: english, hi: hindi };

export function translate(
  language: LanguageCode,
  key: TranslationKey,
  vars: Record<string, string | number> = {}
): string {
  const value = (language === "hi" ? hindi[key as keyof typeof hindi] : undefined) ?? english[key as keyof typeof english] ?? String(key);
  return value.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? `{{${name}}}`));
}
